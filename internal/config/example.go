package config

import (
	"strings"

	"github.com/suprbdev/pdbcore/confx"
)

// ExampleYAML renders the fully-commented reference configuration from the
// Config struct tags and defaults, so the reference can never drift from the
// real config surface. The shared sections carry pdbq-flavoured docs in a few
// places; those are overridden here with pdbr wording.
func ExampleYAML() string {
	var b strings.Builder
	b.WriteString("# pdbr reference configuration.\n")
	b.WriteString("# Generated by `pdbr config example` from the config structs — reference, not for direct use.\n")
	b.WriteString("# Every key is also settable via env (PDBR_SECTION_KEY, double underscore for '_' in names)\n")
	b.WriteString("# or command-line flags; precedence is flags > env > file.\n\n")
	cfg := DefaultConfig()
	b.WriteString(confx.ExampleYAML(&cfg,
		confx.WithDoc("schema.cache_path", "Boot from this schema cache file instead of introspecting (see pdbr schema dump)."),
		confx.WithDoc("schema.functions", "Expose PostgreSQL functions as /rpc/{fn} routes and computed columns."),
		confx.WithDoc("rls.auth.header_prefix", "Header prefix mapped to claims in headers mode, e.g. X-Pdbr-Claim-."),
		confx.WithDoc("rls.claims_prefix", "set_config namespace for request claims. Defaults to pdbq.claims so RLS policies written for pdbq work unchanged."),
		confx.WithDoc("errors.detail", "'dev' exposes full PostgreSQL error detail (plus a pg object) in problem responses; 'prod' sanitizes but passes constraint-violation and bad-input messages through; 'strict' hides every database error message (constraint and column names never leak)."),
	))
	return b.String()
}
