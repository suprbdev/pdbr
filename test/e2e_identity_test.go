package e2e

import (
	"net/http"
	"os"
	"slices"
	"testing"

	"github.com/suprbdev/pdbr/internal/config"
)

// TestIdentityKinds checks that identity BY DEFAULT columns are writable
// (optional on POST, settable by PATCH and PUT, a usable PUT key) while
// identity ALWAYS columns stay read-only.
func TestIdentityKinds(t *testing.T) {
	url := os.Getenv("PDBR_TEST_DATABASE_URL")
	if url == "" {
		t.Skip("PDBR_TEST_DATABASE_URL not set; run `make test-e2e`")
	}
	drop := `DROP SCHEMA IF EXISTS idk CASCADE`
	execDDL(t, url, drop,
		`CREATE SCHEMA idk`,
		`CREATE TABLE idk.soft (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL)`,
		`CREATE TABLE idk.hard (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY, name text NOT NULL)`,
	)
	t.Cleanup(func() { execDDL(t, url, drop) })
	srv := testServer(t, func(c *config.Config) { c.Schema.Schemas = []string{"idk"} })
	base := srv.URL + "/api"

	var r row
	sendJSON(t, http.MethodPost, base+"/soft", `{"name": "auto"}`, http.StatusCreated, nil)
	sendJSON(t, http.MethodPost, base+"/soft", `{"id": 100, "name": "explicit"}`, http.StatusCreated, nil)
	sendJSON(t, http.MethodPatch, base+"/soft/100", `{"id": 200}`, http.StatusOK, &r)
	if rowID(t, r) != 200 {
		t.Fatalf("PATCH id: %v", r)
	}
	res := sendJSON(t, http.MethodPut, base+"/soft/300", `{"name": "put"}`, http.StatusCreated, &r)
	if rowID(t, r) != 300 || res.Header.Get("Location") == "" {
		t.Fatalf("PUT by identity key: %v %v", r, res.Header)
	}
	sendJSON(t, http.MethodPut, base+"/soft", `{"id": 300, "name": "upserted"}`, http.StatusOK, &r)
	if r["name"] != "upserted" {
		t.Fatalf("PUT by default target: %v", r)
	}
	var rows []row
	getJSON(t, base+"/soft?order=id", &rows)
	if got := ids(rows, "id"); !slices.Equal(got, []int{1, 200, 300}) {
		t.Fatalf("ids = %v", got)
	}

	sendJSON(t, http.MethodPost, base+"/hard", `{"name": "auto"}`, http.StatusCreated, nil)
	res, body := send(t, http.MethodPost, base+"/hard", `{"id": 5, "name": "x"}`, nil)
	wantProblem(t, res, body, http.StatusBadRequest, "column_readonly")
	res, body = send(t, http.MethodPatch, base+"/hard/1", `{"id": 5}`, nil)
	wantProblem(t, res, body, http.StatusBadRequest, "column_readonly")
	res, body = send(t, http.MethodPut, base+"/hard/1", `{"name": "x"}`, nil)
	wantProblem(t, res, body, http.StatusMethodNotAllowed, "method_not_allowed")

	insert := openAPIProperties(t, srv, "soft.insert")
	if !slices.Contains(insert, "id") || slices.Contains(openAPIProperties(t, srv, "hard.insert"), "id") {
		t.Errorf("insert schemas: soft %v hard %v", insert, openAPIProperties(t, srv, "hard.insert"))
	}
}
